/** 版本徽章文案：v4.9.0 · 08-31 07:30 上线（无构建时间只显示版本号） */
export function versionBadgeText(): string {
  if (!BUILD_AT) return APP_VERSION;
  const d = new Date(BUILD_AT);
  if (isNaN(d.getTime())) return APP_VERSION;
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  const hh = String(d.getHours()).padStart(2, '0');
  const mi = String(d.getMinutes()).padStart(2, '0');
  return `${APP_VERSION} · ${mm}-${dd} ${hh}:${mi} 上线`;
}

